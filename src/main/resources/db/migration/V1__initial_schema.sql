-- UniversalShield initial schema. Portable between PostgreSQL 13+ and H2 (MODE=PostgreSQL).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL,
    display_name  VARCHAR(80)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE user_preferences (
    user_id              BIGINT      NOT NULL PRIMARY KEY,
    retention_days       INTEGER     NOT NULL DEFAULT 90,
    store_input_excerpts BOOLEAN     NOT NULL DEFAULT TRUE,
    default_category     VARCHAR(30) NOT NULL DEFAULT 'MESSAGE',
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_prefs_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_prefs_retention CHECK (retention_days BETWEEN 1 AND 365),
    CONSTRAINT ck_prefs_category CHECK (default_category IN ('MESSAGE', 'URL', 'TRANSACTION', 'CALL', 'APP_PERMISSION'))
);

CREATE TABLE scans (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID         NOT NULL,
    user_id           BIGINT       NOT NULL,
    category          VARCHAR(30)  NOT NULL,
    risk_score        INTEGER      NOT NULL,
    risk_level        VARCHAR(10)  NOT NULL,
    evidence_strength VARCHAR(10)  NOT NULL,
    sources           VARCHAR(100) NOT NULL,
    ruleset_version   VARCHAR(30)  NOT NULL,
    detector_versions VARCHAR(400) NOT NULL,
    input_excerpt     VARCHAR(600),
    subject_hash      VARCHAR(64),
    amount            NUMERIC(18, 2),
    reasons           TEXT         NOT NULL,
    recommendations   TEXT         NOT NULL,
    notes             TEXT         NOT NULL,
    disclaimers       TEXT         NOT NULL,
    demo              BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_scans_public_id UNIQUE (public_id),
    CONSTRAINT fk_scans_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_scans_score CHECK (risk_score BETWEEN 0 AND 100),
    CONSTRAINT ck_scans_level CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_scans_evidence CHECK (evidence_strength IN ('LIMITED', 'MODERATE', 'STRONG')),
    CONSTRAINT ck_scans_category CHECK (category IN ('MESSAGE', 'URL', 'TRANSACTION', 'CALL', 'APP_PERMISSION'))
);

CREATE INDEX ix_scans_user_created ON scans (user_id, created_at);
CREATE INDEX ix_scans_user_category ON scans (user_id, category);
CREATE INDEX ix_scans_user_level ON scans (user_id, risk_level);
CREATE INDEX ix_scans_user_subject ON scans (user_id, subject_hash);
CREATE INDEX ix_scans_created ON scans (created_at);

CREATE TABLE scan_indicators (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id         BIGINT       NOT NULL,
    code            VARCHAR(60)  NOT NULL,
    indicator_group VARCHAR(60)  NOT NULL,
    title           VARCHAR(200) NOT NULL,
    explanation     VARCHAR(600) NOT NULL,
    weight          DOUBLE PRECISION NOT NULL,
    detector_id     VARCHAR(40)  NOT NULL,
    source          VARCHAR(20)  NOT NULL,
    evidence        VARCHAR(200),
    CONSTRAINT fk_indicators_scan FOREIGN KEY (scan_id) REFERENCES scans (id) ON DELETE CASCADE,
    CONSTRAINT ck_indicators_weight CHECK (weight > 0 AND weight <= 1),
    CONSTRAINT ck_indicators_source CHECK (source IN ('LOCAL_HEURISTIC', 'TRAINED_MODEL', 'VERIFIED_EXTERNAL'))
);

CREATE INDEX ix_indicators_scan ON scan_indicators (scan_id);

CREATE TABLE detector_metadata (
    detector_id  VARCHAR(40)  NOT NULL PRIMARY KEY,
    display_name VARCHAR(120) NOT NULL,
    version      VARCHAR(40)  NOT NULL,
    categories   VARCHAR(120) NOT NULL,
    source_type  VARCHAR(20)  NOT NULL,
    description  VARCHAR(600) NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE audit_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT,
    event_type VARCHAR(40)  NOT NULL,
    detail     VARCHAR(300),
    ip_hash    VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX ix_audit_created ON audit_events (created_at);
CREATE INDEX ix_audit_type_created ON audit_events (event_type, created_at);
